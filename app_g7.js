// ----------------------------------------------------------------------------
window.experiments_g7[2] = {
  init: function(ctrl, canvas, readout) {
    ctrl.innerHTML = `
      <div class="control-row">
        <label><i class="fa-solid fa-train"></i> 當前起點站: <span id="stationName" class="val-badge">媽閣站 (x = -3)</span></label>
        <button id="btnStation1" class="btn-sm btn-secondary">媽閣 (-3)</button>
        <button id="btnStation2" class="btn-sm btn-secondary">海洋 (0)</button>
        <button id="btnStation3" class="btn-sm btn-secondary">馬會 (+2)</button>
        <button id="btnStation4" class="btn-sm btn-secondary">氹仔碼頭 (+6)</button>
      </div>
      <div class="control-row">
        <label><i class="fa-solid fa-arrows-left-right"></i> 運行位移向量: <span id="valDisplace" class="val-badge">+5 km (向東)</span></label>
        <input type="range" id="rngDisplace" min="-8" max="8" step="1" value="5">
      </div>
      <div class="control-row">
        <button id="btnMoveTrain" class="btn-sm btn-primary"><i class="fa-solid fa-play"></i> 平移運行列車</button>
        <button id="btnResetTrain" class="btn-sm btn-outline"><i class="fa-solid fa-rotate-left"></i> 重置起點</button>
      </div>
    `;

    const ctx = setupCanvas(canvas);
    let currentX = -3;
    let targetX = 2;
    let animProgress = 1.0;
    let animId = null;

    function render(trainPos) {
      ctx.clearRect(0, 0, 700, 420);
      ctx.fillStyle = '#f8fafc';
      ctx.fillRect(0, 0, 700, 420);

      // Title
      ctx.fillStyle = '#1e293b';
      ctx.font = 'bold 15px sans-serif';
      ctx.fillText('澳門輕軌氹仔線數軸位移向量模型 (原點 0: 海洋站, 向東為正)', 60, 40);

      // Number line
      const axisY = 220;
      ctx.strokeStyle = '#334155';
      ctx.lineWidth = 3;
      ctx.beginPath();
      ctx.moveTo(50, axisY);
      ctx.lineTo(650, axisY);
      ctx.stroke();

      // Arrow
      ctx.fillStyle = '#334155';
      ctx.beginPath();
      ctx.moveTo(650, axisY - 6);
      ctx.lineTo(662, axisY);
      ctx.lineTo(650, axisY + 6);
      ctx.fill();

      // Ticks (-6 to +8)
      const scale = 40; // 40px per km
      const originX = 350;

      for (let k = -6; k <= 7; k++) {
        const tx = originX + k * scale;
        ctx.beginPath();
        ctx.moveTo(tx, axisY - 8);
        ctx.lineTo(tx, axisY + 8);
        ctx.strokeStyle = k === 0 ? '#2563eb' : '#64748b';
        ctx.lineWidth = k === 0 ? 3 : 1;
        ctx.stroke();

        ctx.fillStyle = k === 0 ? '#2563eb' : '#64748b';
        ctx.font = k === 0 ? 'bold 13px sans-serif' : '11px sans-serif';
        ctx.textAlign = 'center';
        ctx.fillText(k > 0 ? `+${k}` : `${k}`, tx, axisY + 24);
      }

      // Stations
      const stations = [
        { name: '媽閣', x: -3 },
        { name: '海洋 (原點)', x: 0 },
        { name: '馬會', x: 2 },
        { name: '排角', x: 4 },
        { name: '氹仔碼頭', x: 6 }
      ];

      stations.forEach(s => {
        const sx = originX + s.x * scale;
        ctx.fillStyle = '#475569';
        ctx.beginPath(); ctx.arc(sx, axisY, 5, 0, Math.PI * 2); ctx.fill();
        ctx.font = '11px sans-serif';
        ctx.fillText(s.name, sx, axisY - 14);
      });

      // Vector Arrow from start to current animated position
      const startPx = originX + currentX * scale;
      const curPx = originX + trainPos * scale;

      if (Math.abs(curPx - startPx) > 1) {
        ctx.strokeStyle = '#10b981';
        ctx.lineWidth = 4;
        ctx.beginPath();
        ctx.moveTo(startPx, axisY - 30);
        ctx.lineTo(curPx, axisY - 30);
        ctx.stroke();

        // Vector arrow head
        const dir = curPx > startPx ? 1 : -1;
        ctx.fillStyle = '#10b981';
        ctx.beginPath();
        ctx.moveTo(curPx, axisY - 30);
        ctx.lineTo(curPx - dir * 10, axisY - 36);
        ctx.lineTo(curPx - dir * 10, axisY - 24);
        ctx.fill();

        ctx.fillStyle = '#047857';
        ctx.font = 'bold 13px sans-serif';
        const dispVal = (trainPos - currentX);
        ctx.fillText(`位移向量 s⃗ = ${dispVal >= 0 ? '+' : ''}${dispVal.toFixed(1)} km`, (startPx + curPx) / 2, axisY - 45);
      }

      // Train Graphic
      ctx.fillStyle = '#2563eb';
      ctx.fillRect(curPx - 20, axisY - 12, 40, 24);
      ctx.fillStyle = '#ffffff';
      ctx.fillRect(curPx - 15, axisY - 8, 12, 10);
      ctx.fillRect(curPx + 3, axisY - 8, 12, 10);
      ctx.fillStyle = '#1e3a8a';
      ctx.beginPath(); ctx.arc(curPx - 10, axisY + 12, 4, 0, Math.PI * 2); ctx.fill();
      ctx.beginPath(); ctx.arc(curPx + 10, axisY + 12, 4, 0, Math.PI * 2); ctx.fill();

      ctx.textAlign = 'left';
    }

    function update() {
      const disp = parseFloat(document.getElementById('rngDisplace').value);
      document.getElementById('valDisplace').textContent = `${disp >= 0 ? '+' : ''}${disp} km (${disp >= 0 ? '向東' : '向西'})`;
      targetX = currentX + disp;

      const dist = Math.abs(disp);
      readout.innerHTML = `
        <span class="readout-item">起點坐標: <strong>x1 = ${currentX} km</strong></span>
        <span class="readout-item">目標終點坐標: <strong>x2 = ${targetX} km</strong></span>
        <span class="readout-item">位移向量: <strong style="color:${disp>=0?'#059669':'#dc2626'}">${disp >= 0 ? '+' : ''}${disp} km</strong></span>
        <span class="readout-item">標量路程 (絕對值): <strong>|${disp}| = ${dist} km</strong></span>
      `;
      render(currentX);
    }

    document.getElementById('rngDisplace').addEventListener('input', update);

    document.getElementById('btnStation1').onclick = () => { currentX = -3; document.getElementById('stationName').textContent = '媽閣站 (x = -3)'; update(); };
    document.getElementById('btnStation2').onclick = () => { currentX = 0; document.getElementById('stationName').textContent = '海洋站 (x = 0)'; update(); };
    document.getElementById('btnStation3').onclick = () => { currentX = 2; document.getElementById('stationName').textContent = '馬會站 (x = +2)'; update(); };
    document.getElementById('btnStation4').onclick = () => { currentX = 6; document.getElementById('stationName').textContent = '氹仔碼頭 (x = +6)'; update(); };

    document.getElementById('btnMoveTrain').onclick = () => {
      const disp = parseFloat(document.getElementById('rngDisplace').value);
      const startX = currentX;
      targetX = currentX + disp;
      let startTime = null;

      function step(timestamp) {
        if (!startTime) startTime = timestamp;
        const progress = Math.min((timestamp - startTime) / 1000, 1);
        const cur = startX + (targetX - startX) * progress;
        render(cur);
        if (progress < 1) {
          requestAnimationFrame(step);
        } else {
          currentX = targetX;
          update();
        }
      }
      requestAnimationFrame(step);
    };

    document.getElementById('btnResetTrain').onclick = () => {
      currentX = 0;
      update();
    };

    update();
  }
};

