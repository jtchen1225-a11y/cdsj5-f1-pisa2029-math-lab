function initUI() {
  // Stepper
  const weekSelect = document.getElementById('weekSelect');
  weekSelect.innerHTML = '';
  LESSONS_DATA.forEach(l => {
    const opt = document.createElement('option');
    opt.value = l.week;
    opt.textContent = `第 ${String(l.week).padStart(2, '0')} 週：${l.title.split('——')[0]}`;
    weekSelect.appendChild(opt);
  });

  weekSelect.addEventListener('change', (e) => {
    loadLesson(parseInt(e.target.value));
  });

  document.getElementById('btnPrevWeek').addEventListener('click', () => {
    if (currentWeek > 1) loadLesson(currentWeek - 1);
  });

  document.getElementById('btnNextWeek').addEventListener('click', () => {
    if (currentWeek < 30) loadLesson(currentWeek + 1);
  });

  // Filter Tabs
  document.querySelectorAll('.filter-tab').forEach(tab => {
    tab.addEventListener('click', (e) => {
      document.querySelectorAll('.filter-tab').forEach(t => t.classList.remove('active'));
      e.target.classList.add('active');
      currentFilter = e.target.dataset.filter;
      renderSidebar();
    });
  });

  // Search
  document.getElementById('lessonSearch').addEventListener('input', () => {
    renderSidebar();
  });

  // Sidebar toggle
  document.getElementById('sidebarToggle').addEventListener('click', () => {
    document.getElementById('sidebar').classList.toggle('collapsed');
  });

  // CER Toggle
  const btnToggleCER = document.getElementById('btnToggleCER');
  if (btnToggleCER) {
    btnToggleCER.addEventListener('click', () => {
      const cerCard = document.getElementById('cerCard');
      cerCard.classList.toggle('collapsed');
    });
  }
  const cerHeader = document.getElementById('cerHeader');
  if (cerHeader) {
    cerHeader.addEventListener('click', () => {
      document.getElementById('cerCard').classList.toggle('collapsed');
    });
  }

  // Solution Toggle
  const btnToggleSolution = document.getElementById('btnToggleSolution');
  if (btnToggleSolution) {
    btnToggleSolution.addEventListener('click', () => {
      const box = document.getElementById('solutionBox');
      const btnText = document.getElementById('solutionBtnText');
      if (box.style.display === 'none') {
        box.style.display = 'block';
        btnText.textContent = '隱藏參考解答與解析';
      } else {
        box.style.display = 'none';
        btnText.textContent = '查看參考解答與思維解析';
      }
    });
  }

  // OMML XML Toggle & Copy
  const btnCopyOmml = document.getElementById('btnCopyOmml');
  if (btnCopyOmml) {
    btnCopyOmml.addEventListener('click', () => {
      const curLesson = LESSONS_DATA.find(l => l.week === currentWeek);
      if (curLesson && curLesson.omml_xml) {
        navigator.clipboard.writeText(curLesson.omml_xml).then(() => {
          showToast('✔ 已成功複製原生 OMML 公式代碼！可在 Word 中直接粘貼。');
        }).catch(() => {
          showToast('請手動選取 XML 代碼複製。');
        });
      }
    });
  }

  const btnToggleOmmlXml = document.getElementById('btnToggleOmmlXml');
  if (btnToggleOmmlXml) {
    btnToggleOmmlXml.addEventListener('click', () => {
      const box = document.getElementById('ommlXmlBox');
      box.style.display = box.style.display === 'none' ? 'block' : 'none';
    });
  }

  // Fullscreen
  document.getElementById('btnFullscreen').addEventListener('click', () => {
    if (!document.fullscreenElement) {
      document.documentElement.requestFullscreen();
    } else {
      document.exitFullscreen();
    }
  });

  // Record Data Button
  const btnRecordData = document.getElementById('btnRecordData');
  if (btnRecordData) {
    btnRecordData.addEventListener('click', () => {
      recordCurrentData();
    });
  }

  const btnResetExp = document.getElementById('btnResetExp');
  if (btnResetExp) {
    btnResetExp.addEventListener('click', () => {
      loadLesson(currentWeek);
      showToast('實驗已重置。');
    });
  }

  renderSidebar();
}

function renderSidebar() {
  const list = document.getElementById('lessonList');
  list.innerHTML = '';
  const query = document.getElementById('lessonSearch').value.toLowerCase();

  const filtered = LESSONS_DATA.filter(l => {
    if (currentFilter === 't1' && l.week > 15) return false;
    if (currentFilter === 't2' && l.week <= 15) return false;
    if (query && !l.title.toLowerCase().includes(query) && !l.unit.toLowerCase().includes(query)) return false;
    return true;
  });

  filtered.forEach(l => {
    const item = document.createElement('div');
    item.className = `lesson-item ${l.week === currentWeek ? 'active' : ''}`;
    item.innerHTML = `
      <div class="item-week">第 ${String(l.week).padStart(2, '0')} 週</div>
      <div class="item-title">${l.title.split('——')[0]}</div>
      <div class="item-domain">${l.domain}</div>
    `;
    item.addEventListener('click', () => loadLesson(l.week));
    list.appendChild(item);
  });
}

function loadLesson(weekNum) {
  currentWeek = weekNum;
  document.getElementById('weekSelect').value = weekNum;

  const lesson = LESSONS_DATA.find(l => l.week === weekNum);
  if (!lesson) return;

  // Banner
  document.getElementById('bannerWeek').textContent = `第 ${String(lesson.week).padStart(2, '0')} 週`;
  document.getElementById('bannerDomain').textContent = lesson.domain;
  document.getElementById('bannerUnit').textContent = lesson.unit;
  document.getElementById('bannerTitle').textContent = lesson.title;
  document.getElementById('bannerCoords').textContent = lesson.pisa_coords;

  // Context & Misconception
  document.getElementById('contextText').textContent = lesson.text_scrutiny;
  document.getElementById('misconceptionText').textContent = lesson.misconception;

  // Guide
  document.getElementById('expPrinciple').textContent = `★ 原理解析：${lesson.exp_principle}`;
  const stepsList = document.getElementById('expStepsList');
  stepsList.innerHTML = '';
  lesson.exp_steps.forEach(st => {
    const li = document.createElement('li');
    li.textContent = st;
    stepsList.appendChild(li);
  });

  // CER Courtroom
  document.getElementById('cerClaim').textContent = lesson.cer.claim;
  document.getElementById('cerEvidence').textContent = lesson.cer.evidence;
  document.getElementById('cerReasoning').textContent = lesson.cer.reasoning;
  document.getElementById('cerRebuttal').textContent = lesson.cer.rebuttal;

  // CPS Challenge
  document.getElementById('cpsChallengeText').textContent = lesson.cps_challenge;
  document.getElementById('solutionContent').innerHTML = lesson.cps_solution;
  document.getElementById('solutionBox').style.display = 'none';
  const solBtnText = document.getElementById('solutionBtnText');
  if (solBtnText) solBtnText.textContent = '查看參考解答與思維解析';

  // OMML Formula Card
  document.getElementById('ommlTitle').textContent = lesson.omml_title;
  document.getElementById('mathjaxFormula').innerHTML = `$$${lesson.tex_formula}$$`;
  document.getElementById('ommlXmlText').value = lesson.omml_xml;
  document.getElementById('ommlXmlBox').style.display = 'none';

  // Render Table
  renderObsTable(lesson);

  // Init Sandbox Experiment
  const ctrl = document.getElementById('sandboxControls');
  const canvas = document.getElementById('mainCanvas');
  const readout = document.getElementById('sandboxReadout');
  document.getElementById('sandboxName').textContent = lesson.exp_name;

  if (window.experiments_g7 && window.experiments_g7[weekNum]) {
    window.experiments_g7[weekNum].init(ctrl, canvas, readout);
  } else {
    ctrl.innerHTML = '<p class="text-muted">本實驗互動引擎載入中...</p>';
    readout.innerHTML = '<span class="readout-item">狀態: 正常</span>';
  }

  // Update Sidebar
  renderSidebar();

  // MathJax Typeset
  if (window.MathJax && window.MathJax.typesetPromise) {
    window.MathJax.typesetPromise([document.getElementById('mathjaxFormula')]).catch(() => {});
  }
}

function renderObsTable(lesson) {
  const thead = document.getElementById('obsThead');
  const tbody = document.getElementById('obsTbody');

  thead.innerHTML = '<tr>' + lesson.table_headers.map(h => `<th>${h}</th>`).join('') + '</tr>';

  tbody.innerHTML = lesson.table_rows.map(row => {
    return '<tr>' + row.map(cell => `<td>${cell}</td>`).join('') + '</tr>';
  }).join('');
}

function recordCurrentData() {
  const tbody = document.getElementById('obsTbody');
  const readout = document.getElementById('sandboxReadout');
  const items = readout.querySelectorAll('.readout-item strong');

  const row = document.createElement('tr');
  row.style.background = '#e0f2fe';
  const timeStr = new Date().toLocaleTimeString();

  let html = `<td>記錄 (${timeStr})</td>`;
  items.forEach((it, i) => {
    if (i < 4) html += `<td>${it.textContent}</td>`;
  });
  while (row.children.length < 5) html += '<td>✔ 已記錄</td>';
  row.innerHTML = html;
  tbody.appendChild(row);
  showToast('✔ 成功記錄當前動態實驗數據！');
}

function showToast(msg) {
  const toast = document.getElementById('toast');
  toast.textContent = msg;
  toast.className = 'toast show';
  setTimeout(() => { toast.className = toast.className.replace('show', ''); }, 2500);
}
