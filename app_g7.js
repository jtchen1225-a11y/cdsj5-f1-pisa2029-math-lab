// Helper: Setup Canvas resolution
function setupCanvas(canvas) {
  const ctx = canvas.getContext('2d');
  const dpr = window.devicePixelRatio || 1;
  const rect = canvas.getBoundingClientRect();
  if (canvas.width !== 700 || canvas.height !== 420) {
    canvas.width = 700;
    canvas.height = 420;
  }
  return ctx;
}

