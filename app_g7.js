// 第 03 週：工業公差邊界與絕對值不等式篩檢台 (|x - x0| ≤ δ)
// ----------------------------------------------------------------------------
window.experiments_g7[3] = {
  init: function(ctrl, canvas, readout) {
    ctrl.innerHTML = `
      <div class="control-row">
        <label><i class="fa-solid fa-bullseye"></i> 標稱直徑 x0: <span id="valX0" class="val-badge">50.00 mm</span></label>
        <input type="range" id="rngX0" min="40" max="60" step="1" value="50">
      </div>
      <div class="control-row">
        <label><i class="fa-solid fa-arrows-split-up-and-left"></i> 容許公差 δ: <span id="valDelta" class="val-badge">±0.05 mm</span></label>
        <input type="range" id="rngDelta" min="0.01" max="0.10" step="0.01" value="0.05">
      </div>
      <div class="control-row">
        <button id="btnSample" class="btn-sm btn-primary"><i class="fa-solid fa-dice"></i> 隨機生產 10 個零件抽檢</button>
        <button id="btnClearSample" class="btn-sm btn-outline"><i class="fa-solid fa-trash"></i> 清空樣本</button>
      </div>
    `;

    const ctx = setupCanvas(canvas);
    let samples = [50.03, 49.96, 50.07, 49.98, 50.01, 49.94, 50.05, 50.02];

    function update() {
      const x0 = parseFloat(document.getElementById('rngX0').value);
      const delta = parseFloat(document.getElementById('rngDelta').value);
      document.getElementById('valX0').textContent = x0.toFixed(2) + ' mm';
      document.getElementById('valDelta').textContent = '±' + delta.toFixed(2) + ' mm';

      const minX = x0 - delta;
      const maxX = x0 + delta;

      let passCount = 0;
      samples.forEach(s => {
        if (Math.abs(s - x0) <= delta + 1e-6) passCount++;
      });
      const passRate = samples.length > 0 ? (passCount / samples.length * 100).toFixed(1) : 100;

      readout.innerHTML = `
        <span class="readout-item">合格直徑區間: <strong>[${minX.toFixed(2)}, ${maxX.toFixed(2)}] mm</strong></span>
        <span class="readout-item">檢驗樣本數: <strong>${samples.length} 個</strong></span>
        <span class="readout-item">合格品數: <strong style="color:#059669">${passCount} 個</strong></span>
        <span class="readout-item">廢品數: <strong style="color:#dc2626">${samples.length - passCount} 個</strong></span>
        <span class="readout-item">合格率: <strong>${passRate}%</strong></span>
      `;

      ctx.clearRect(0, 0, 700, 420);
      ctx.fillStyle = '#f8fafc';
      ctx.fillRect(0, 0, 700, 420);

      // Title
      ctx.fillStyle = '#1e293b';
      ctx.font = 'bold 15px sans-serif';
      ctx.fillText(`工業零件尺寸絕對值公差邊界: |x - ${x0.toFixed(2)}| ≤ ${delta.toFixed(2)} mm`, 60, 40);

      // Axis for tolerance inspection
      const cy = 200;
      const scale = 1600; // px per mm
      const centerPx = 350;

      // Draw safe tolerance zone
      const leftSafe = centerPx - delta * scale;
      const rightSafe = centerPx + delta * scale;

      ctx.fillStyle = 'rgba(16, 185, 129, 0.2)';
      ctx.fillRect(leftSafe, 80, rightSafe - leftSafe, 240);

      ctx.strokeStyle = '#059669';
      ctx.lineWidth = 2;
      ctx.strokeRect(leftSafe, 80, rightSafe - leftSafe, 240);

      // Main axis
      ctx.strokeStyle = '#334155';
      ctx.lineWidth = 2;
      ctx.beginPath(); ctx.moveTo(60, cy); ctx.lineTo(640, cy); ctx.stroke();

      // Center x0 line
      ctx.strokeStyle = '#2563eb';
      ctx.setLineDash([4, 4]);
      ctx.beginPath(); ctx.moveTo(centerPx, 70); ctx.lineTo(centerPx, 330); ctx.stroke();
      ctx.setLineDash([]);

      ctx.fillStyle = '#2563eb';
      ctx.font = 'bold 12px sans-serif';
      ctx.textAlign = 'center';
      ctx.fillText(`基準中心 x0 = ${x0.toFixed(2)}`, centerPx, 65);
      ctx.fillText(`下界: ${minX.toFixed(2)}`, leftSafe, 345);
      ctx.fillText(`上界: ${maxX.toFixed(2)}`, rightSafe, 345);

      // Plot sample points
      samples.forEach((val, idx) => {
        const dev = val - x0;
        const px = centerPx + dev * scale;
        const py = 120 + (idx % 8) * 22;
        const isPass = Math.abs(dev) <= delta + 1e-6;

        ctx.fillStyle = isPass ? '#059669' : '#dc2626';
        ctx.beginPath();
        ctx.arc(px, py, 6, 0, Math.PI * 2);
        ctx.fill();

        ctx.font = '10px sans-serif';
        ctx.fillText(val.toFixed(2), px, py - 9);
      });
      ctx.textAlign = 'left';
    }

    document.getElementById('rngX0').addEventListener('input', update);
    document.getElementById('rngDelta').addEventListener('input', update);
    document.getElementById('btnSample').onclick = () => {
      const x0 = parseFloat(document.getElementById('rngX0').value);
      for (let i = 0; i < 5; i++) {
        const randDev = (Math.random() - 0.48) * 0.16;
        samples.push(parseFloat((x0 + randDev).toFixed(3)));
      }
      update();
    };
    document.getElementById('btnClearSample').onclick = () => {
      samples = [];
      update();
    };

    update();
  }
};

